export const SUPPORTED_LOCALES = Object.keys(STRINGS);

/** Normalise « fr-FR », « FR », « fr_fr »… -> « fr » ; défaut « fr ». */
export function normalizeLocale(locale) {
  const short = String(locale ?? "")
    .toLowerCase()
    .replace("_", "-")
    .split("-")[0];
  return SUPPORTED_LOCALES.includes(short) ? short : DEFAULT_LOCALE;
}

/**
 * Renvoie une fonction `t(key, vars?)` pour la locale donnée. Une clé absente
 * de la locale retombe sur le français, puis sur la clé elle-même. `vars`
 * remplace les gabarits `{name}` (utilisé par `tablePrompt*` -> `{size}`).
 */
export function makeT(locale) {
  const table = STRINGS[normalizeLocale(locale)];
  return (key, vars) => {
    let s = table[key] ?? STRINGS.fr[key] ?? key;
    if (vars) {
      for (const [k, v] of Object.entries(vars)) {
        s = s.replace(`{${k}}`, v);
      }
    }
    return s;
  };
}
